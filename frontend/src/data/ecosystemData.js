export function getApp(id) {
  return ECOSYSTEM_APPS.find(a => a.id === id);
}

export function getConnectedApps(id) {
  const app = getApp(id);
  if (!app) return [];
  return app.connects.map(cid => getApp(cid)).filter(Boolean);
}
