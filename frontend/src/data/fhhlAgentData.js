export function getFHHLAgent(id)      { return FHHL_AGENTS.find(a => a.id === id) || null; }
export function getFHHLDept(id)       { return FHHL_DEPARTMENTS[id] || { id, label: id, icon: '🏆', color: FHHL_ACCENT, desc: '' }; }
export function getFHHLRankTitle(lvl) { return FHHL_RANKS[lvl] || 'Unknown'; }

export function getFHHLStatusMeta(status) {
  const map = {
    active:   { label: 'ACTIVE',    color: '#34D399', bg: 'rgba(52,211,153,0.12)'  },
    standby:  { label: 'STANDBY',   color: '#F59E0B', bg: 'rgba(245,158,11,0.12)' },
    training: { label: 'TRAINING',  color: '#60A5FA', bg: 'rgba(96,165,250,0.12)' },
    locked:   { label: 'LOCKED',    color: '#6B7280', bg: 'rgba(107,114,128,0.12)' },
  };
  return map[status] || map.standby;
}
