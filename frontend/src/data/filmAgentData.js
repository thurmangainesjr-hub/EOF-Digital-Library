export function getFilmAgent(id) {
  return FILM_AGENTS.find(a => a.id === id) || null;
}

export function getFilmDept(key) {
  return FILM_DEPARTMENTS[key] || { label: key, color: '#EF4444', icon: '🎬', desc: '' };
}

export function getFilmStatusMeta(status) {
  const map = {
    active:   { label: 'Active',   color: '#10B981', bg: 'rgba(16,185,129,0.12)' },
    standby:  { label: 'Standby',  color: '#38BDF8', bg: 'rgba(56,189,248,0.12)' },
    training: { label: 'Training', color: '#F59E0B', bg: 'rgba(245,158,11,0.12)' },
    locked:   { label: 'Locked',   color: '#6B7280', bg: 'rgba(107,114,128,0.12)' },
  };
  return map[status] || map.standby;
}

export function getFilmRankTitle(level) {
  const r = FILM_RANKS.find(r => r.level === level);
  return r ? r.title : 'Unknown';
}
