export const DIVISIONS_META = DIVISIONS;

export function getAgent(id) {
  return AGENTS.find(a => a.id === id) || null;
}

export function getDivisionMeta(key) {
  return DIVISIONS[key] || { label: key, color: '#7C3AED', icon: '⚡', desc: '' };
}

export function getStatusMeta(status) {
  const map = {
    active:   { label: 'Active',   color: '#10B981', bg: 'rgba(16,185,129,0.12)' },
    standby:  { label: 'Standby',  color: '#38BDF8', bg: 'rgba(56,189,248,0.12)' },
    training: { label: 'Training', color: '#F59E0B', bg: 'rgba(245,158,11,0.12)' },
    locked:   { label: 'Locked',   color: '#6B7280', bg: 'rgba(107,114,128,0.12)' },
  };
  return map[status] || map.standby;
}

export function getRankTitle(level) {
  const r = RANKS.find(r => r.level === level);
  return r ? r.title : 'Unknown';
}
