export function getMusicAgent(id) {
  return MUSIC_AGENTS.find(a => a.id === id) || null;
}

export function getMusicDept(key) {
  return MUSIC_DEPARTMENTS[key] || { label: key, color: '#D4AF37', icon: '🎵', desc: '' };
}

export function getMusicStatusMeta(status) {
  const map = {
    active:   { label: 'Active',   color: '#10B981', bg: 'rgba(16,185,129,0.12)' },
    standby:  { label: 'Standby',  color: '#38BDF8', bg: 'rgba(56,189,248,0.12)' },
    training: { label: 'Training', color: '#F59E0B', bg: 'rgba(245,158,11,0.12)' },
    locked:   { label: 'Locked',   color: '#6B7280', bg: 'rgba(107,114,128,0.12)' },
  };
  return map[status] || map.standby;
}

export function getMusicRankTitle(level) {
  const r = MUSIC_RANKS.find(r => r.level === level);
  return r ? r.title : 'Unknown';
}
